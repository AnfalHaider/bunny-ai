const STRINGS = { en, es, fr, ar };

/** The direction a language is written in. */
export function directionOf(code) {
  return code === 'ar' ? 'rtl' : 'ltr';
}

/**
 * Translate a key.
 * @param {string} key
 * @param {string} code
 */
export function t(key, code = 'en') {
  const table = STRINGS[code] ?? STRINGS.en;
  return table[key] ?? STRINGS.en[key] ?? key;
}

/**
 * Translate the whole page.
 *
 * Elements marked with data-i18n get their text; data-i18n-placeholder gets
 * the placeholder; data-i18n-label gets the accessible label.
 */
export function applyLanguage(code) {
  const lang = STRINGS[code] ? code : 'en';
  document.documentElement.lang = lang;
  document.documentElement.dir = directionOf(lang);

  for (const node of document.querySelectorAll('[data-i18n]')) {
    const key = node.getAttribute('data-i18n');
    const text = t(key, lang);
    if (text !== key) node.textContent = text; // an unknown key keeps the page's own words
  }
  for (const node of document.querySelectorAll('[data-i18n-placeholder]')) {
    const key = node.getAttribute('data-i18n-placeholder');
    node.placeholder = t(key, lang);
  }
  for (const node of document.querySelectorAll('[data-i18n-label]')) {
    const key = node.getAttribute('data-i18n-label');
    node.setAttribute('aria-label', t(key, lang));
  }
  return lang;
}

// The agent's screens (i18n-agent.js), merged into each language's table.
for (const [code, table] of Object.entries({ en, es, fr, ar })) Object.assign(table, AGENT_STRINGS[code]);

/** Fill {name} placeholders: fill('Show all {n} lines', { n: 40 }). */
export function fill(text, vars = {}) {
  return String(text).replace(/\{(\w+)\}/g, (whole, k) => (vars[k] ?? whole));
}
