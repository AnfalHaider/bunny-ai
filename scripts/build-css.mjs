// Builds src/ui/app.css from the design system.
// Source of truth: docs/design/bunny-design-system.css + docs/design/bunny-app-bindings.css
// Run: npm run build:css
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const parts = ['docs/design/bunny-design-system.css', 'docs/design/bunny-app-bindings.css'];
const header = `/* GENERATED by scripts/build-css.mjs — do not edit by hand.
   Edit ${parts.join(' and ')}, then run: npm run build:css */\n\n`;
// Build with LF, then compare with what is on disk ignoring line endings. If only the endings differ (a checkout with
// core.autocrlf keeps CRLF, and the committed blob may be CRLF too) the file is left alone, so a rebuild never dirties a
// clean tree. When the content really changed it is written with the existing file's line endings.
const built = header + parts.map((p) => readFileSync(join(root, p), 'utf8').replace(/\r\n/g, '\n')).join('\n\n');
const target = join(root, 'src/ui/app.css');
const existing = existsSync(target) ? readFileSync(target, 'utf8') : null;
if (existing !== null && existing.replace(/\r\n/g, '\n') === built) {
  console.log('src/ui/app.css is up to date (not rewritten)');
} else {
  const css = existing !== null && existing.includes('\r\n') ? built.replace(/\n/g, '\r\n') : built;
  writeFileSync(target, css);
  console.log(`wrote src/ui/app.css (${css.length.toLocaleString()} bytes)`);
}
