// Builds src/ui/app.css from the design system.
// Source of truth: docs/design/bunny-design-system.css + docs/design/bunny-app-bindings.css
// Run: npm run build:css
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const parts = ['docs/design/bunny-design-system.css', 'docs/design/bunny-app-bindings.css'];
const header = `/* GENERATED by scripts/build-css.mjs — do not edit by hand.
   Edit ${parts.join(' and ')}, then run: npm run build:css */\n\n`;
const css = header + parts.map((p) => readFileSync(join(root, p), 'utf8')).join('\n\n');
writeFileSync(join(root, 'src/ui/app.css'), css);
console.log(`wrote src/ui/app.css (${css.length.toLocaleString()} bytes)`);
