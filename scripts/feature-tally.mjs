/**
 * Renders docs/FEATURE-TALLY.md from docs/features.js.
 *
 * One source, one rendered view. The readable tally is generated, never edited
 * by hand, so it cannot drift from what the tests check.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { FEATURES, countBy, byArea } from '../docs/features.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT = join(ROOT, 'docs', 'FEATURE-TALLY.md');

const AREA_ORDER = ['Conversation', 'Providers', 'Artifacts', 'Structure', 'Shell', 'Automation'];

const AREA_TITLES = {
  Conversation: '1. Conversation core',
  Providers: '2. Models and providers',
  Artifacts: '3. Artifacts',
  Structure: '4. Sessions and structure',
  Shell: '5. Shell, settings and platform',
  Automation: '6. Memory, connectors and automation',
};

const AREA_INTRO = {
  Conversation: 'The spine of the product: sending, streaming, keeping and shaping a thread.',
  Providers: 'Which model answers, and how a key gets there honestly.',
  Artifacts: 'The defining surface: something the model made, shown beside the chat.',
  Structure: 'How conversations are organised once there are many.',
  Shell: 'The frame around the conversation.',
  Automation: 'The agentic surfaces: memory, tools, schedules.',
};

const STATUS_LABEL = { D: 'done', P: 'partial', M: 'missing' };

export function render() {
  const done = countBy('D');
  const partial = countBy('P');
  const missing = countBy('M');
  const lines = [];

  lines.push('# Feature tally — reference desktop app → Bunny AI', '');
  lines.push('**Date:** 2026-11-12  ');
  lines.push('**Reference side:** the private feature inventory (kept off the repo) — every row there is');
  lines.push('marked (V) observed in the shipped MSIX/npm artifacts or (I) inferred.  ');
  lines.push('**Bunny side:** this repository, checked by test, not by claim.', '');
  lines.push('Status: **D** done and covered by a test · **P** partial · **M** missing.');
  lines.push('A **D** row names the test that fails if the feature breaks. No test, no **D**.', '');
  lines.push('`scope` says what parity means: **core** (a conversation needs it), **app** (a');
  lines.push('surface a desktop AI app is known for), **platform** (OS/desktop integration), **enterprise**');
  lines.push('(org admin, hardware, cloud-specific).', '');
  lines.push('---', '');

  for (const area of AREA_ORDER) {
    const rows = FEATURES.filter((f) => f.area === area);
    if (!rows.length) continue;
    lines.push(`## ${AREA_TITLES[area]}`, '');
    lines.push(AREA_INTRO[area], '');
    lines.push('| # | Reference feature | Scope | Bunny | Evidence / test |');
    lines.push('|---|---|---|---|---|');
    for (const f of rows) {
      const evidence = f.status === 'D'
        ? `\`${f.test}\``
        : f.note ?? '—';
      lines.push(`| ${f.id} | ${f.name} | ${f.scope} | **${f.status}** | ${evidence} |`);
    }
    lines.push('');
  }

  lines.push('---', '', '## Score', '');
  lines.push(`**${done} of ${FEATURES.length}** features are done and covered by a test.`, '');
  lines.push('| Status | Count |');
  lines.push('|---|---|');
  lines.push(`| done | ${done} |`);
  lines.push(`| partial | ${partial} |`);
  lines.push(`| missing | ${missing} |`);
  lines.push('');
  lines.push('### By area', '');
  lines.push('| Area | done | partial | missing | total |');
  lines.push('|---|---|---|---|---|');
  const areas = byArea();
  for (const area of Object.keys(areas)) {
    const a = areas[area];
    lines.push(`| ${area} | ${a.D} | ${a.P} | ${a.M} | ${a.total} |`);
  }
  lines.push('');
  lines.push('### What this means', '');
  lines.push('Bunny AI now covers the surfaces a desktop AI app is known for: the chat and');
  lines.push('providers spine, artifacts beside the chat, branching, projects, memory, MCP tools,');
  lines.push('schedules, hooks, skills, import, search, a command palette and four languages.', '');
  lines.push('Two rows are still open, both on purpose: **computer use** needs OS-level control');
  lines.push('and an entitlement, and **plugins and marketplaces** would mean running third-party');
  lines.push('code, which this app does not do.', '');
  lines.push('This file is generated by `scripts/feature-tally.mjs` from `docs/features.js`;');
  lines.push('`test/tally.test.js` fails when the committed file is stale.');
  lines.push('');

  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = render();
  await writeFile(OUTPUT, text, 'utf8');
  console.log(`wrote ${OUTPUT}`);
  console.log(`${countBy('D')}/${FEATURES.length} done, ${countBy('P')} partial, ${countBy('M')} missing`);
}
